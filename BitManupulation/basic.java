package BitManupulation;

public class basic {
    public static void main(String[] args) {
        System.out.println(51&42);
        System.out.println(51|42);

        int x=5;
        System.out.println(~x);// one's compliment
        System.out.println(~x+1); // 2's compliment
        System.out.println(-x);// 2's compliment
    }
}
